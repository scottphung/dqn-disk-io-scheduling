def generate_traces(
    validation_trace_directory, disk_model_path, checkpoint_environment_settings
):
    """
    A function to generate a validation set of ASCII traces.

    Generate one trace per seed using seeds 200000 through 200019. Each
    trace starts at time zero and contains the number of requests specified
    by "episode_requests" in Josh's checkpoint. The generator reads two settings
    from the saved DQN checkpoint. The first controls the average time between
    I/O requests, and the second controls the probability that a request is a read.
    Every request is 8 sectors, which is 4 KiB at 512 bytes per sector.

    Reuse Josh's DiskSchedEnv._new_arrival() method from
    python/disksim_env/env.py to generate each request. Read the block
    count from the disk model so the generated logical block addresses fit
    the selected HDD. The generator uses a placeholder cylinder lookup
    because DiskSim resolves the physical location when it replays the
    logical block address.

    Create the output directory and write one
    validation_<seed>.trace file per seed. Each line contains five
    space-separated fields in DiskSim ASCII trace order:

        1. Arrival time in milliseconds from the start of the trace.
        2. Device number, set to 0 for the single-disk setup.
        3. Logical block number (LBN) where the request starts.
        4. Request size in sectors, set to 8.
        5. Operation flag, set to 1 for a read or 0 for a write.

    Args:
        validation_trace_directory (Path): Directory where the trace files
            will be saved. Use a separate directory for each HDD.

        disk_model_path (Path): Path to the DiskSim ``.model`` file that
            contains the HDD's ``Block count`` setting.

        checkpoint_environment_settings (dict): Environment settings from
            checkpoint["env_kwargs"].

            Must contain:
            episode_requests, mean_interarrival_ms, and read_fraction.

    Returns:
        None. The validation workloads are written to disk.

    Raises:
        FileExistsError: A trace with the same name already exists.
            Any traces written before that error remain in the directory.
        KeyError: A required checkpoint environment setting is missing.
        OSError: The model file cannot be read or a trace cannot be written.
    """
    validation_trace_directory.mkdir(parents=True, exist_ok=True)

    # Read the disk block count so the addresses generated for the trace fit the specified disks.

    disk_model_contents = (
        disk_model_path.read_text()
    )  # Navigates to the valid/{hdd}.model file in disksim

    block_count_match = re.search(
        r"Block count\s*=\s*(\d+)", disk_model_contents
    )  # Check the block count line but only want value after equals sign

    disk_block_count = int(
        block_count_match[1]
    )  # Take the found block count and convert to int

    validation_seeds = range(
        200_000, 200_020
    )  # Set 20 different random seeds for validation set.

    requests_per_trace = checkpoint_environment_settings[
        "episode_requests"
    ]  # Keep same number of episodes as Josh used in training

    # Loop through seeds and generate the validation set
    for validation_seed in validation_seeds:

        # Setup the workload for this validation trace.
        # Settings found in Josh's _new_arrival() in python/disksim_env/env.py
        workload_generator = SimpleNamespace(
            np_random=np.random.default_rng(validation_seed),
            _next_t=0.0,
            mean_ia=checkpoint_environment_settings["mean_interarrival_ms"],
            sizes=(8,),  # Use fixed 4KB requests
            nblocks=disk_block_count,
            read_frac=checkpoint_environment_settings["read_fraction"],
            # Josh's code looks up the cylinder. Use 0 since we only save the logical block number.
            sim=SimpleNamespace(lbn_to_pbn=lambda logical_block_number: (0,)),
        )

        # Set uup path and format for trace file saves
        validation_trace_path = (
            validation_trace_directory / f"validation_{validation_seed}.trace"
        )

        # Use "x" so an existing trace can't be overwritten
        with validation_trace_path.open("x") as validation_trace_file:

            for _ in range(requests_per_trace):

                # Generate the next request using Josh's existing code
                DiskSchedEnv._new_arrival(workload_generator)
                generated_request = workload_generator._next_req

                arrival_time_ms = generated_request["t"]
                logical_block_number = generated_request["lbn"]
                request_size_sectors = generated_request["size"]
                read_write_flag = int(generated_request["read"])

                # Arrival time, device number, LBN, sectors, read/write flag
                validation_trace_file.write(
                    f"{arrival_time_ms:.9f} 0 {logical_block_number} "
                    f"{request_size_sectors} {read_write_flag}\n"
                )


