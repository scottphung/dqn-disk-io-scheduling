###################
# STEP 1: Imports #
###################

from pathlib import Path
import sys, csv, json, subprocess
import numpy as np
import torch
import gymnasium as gym
import disksim_env

P = Path(__file__).resolve().parent
sys.path.insert(0, str(P / "examples"))
from baselines import fcfs, evaluate
from utils import build_mlp, activation, greedy

VALID = P.parent / "valid"

###################################################
# STEP 2: Load checkpoint and setup configuration #
###################################################

DISKS = ["cheetah4LP"]  # select the set of HDD's we will be testing

CHECKPOINT = "waiting/for/checkpoint/from/josh"  # Path to the saved checkpoint

disk = DISKS[
    0
]  # running on only one disl right now, so will hard code, but may change later, therefore using acessing from a master list of available disks.

# Load the checkpoint
ck = torch.load(CHECKPOINT, map_location="cpu", weights_only=True)

# Copy the environment settings saved with Josh's trained model.
kw = dict(ck["env_kwargs"])

# Select the HDD configuration and limit requests to 8 sectors (4 KiB).
kw.update(parfile=str(VALID / f"{disk}.parv"), sizes=(8,))

# Create the environment and restart its DiskSim worker every 250 resets to manage memory usage.
env = gym.make("DiskSchedRecycled-v0", recycle_every=250, **kw)

#################################
# STEP 3: Setup the trained DQN #
#################################

# Get the hidden layers saved in the checkpoint
hidden = ck["hidden"]

# Older checkpoints saved one size for two hidden layers
if not isinstance(hidden, list):
    hidden = [hidden, hidden]

# Get the activation function and dropout used during training
act = activation(ck.get("activation", "relu"))
dropout = ck.get("train", {}).get("policy_dropout", 0.0)

# Build the network using the saved input, output, and hidden layer sizes
net = build_mlp(ck["nin"], ck["nout"], hidden, act, dropout)

# Load Josh's trained weights and turn off dropout for evaluation
net.load_state_dict(ck["state_dict"])
net.eval()


# Select the highest valued valid request without random exploration
def dqn(obs, mask, rng):
    return greedy(obs, net, ck["use_mask"], mask, rng)
